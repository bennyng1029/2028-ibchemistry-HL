#!/usr/bin/env node
/* Check translations against the English source and refresh the manifest.
     node tools/i18n-check.js <lang> [pageId ...] [--verbose] [--stats] [--all] [--no-manifest]
   Per overlay file it reports:
     missing   English that has no translation yet
     stale     entries whose English no longer exists (with the closest current English, if any)
     lint      translations that break a rule: placeholders, tags, formula/unit/sub/sup contents, links,
               numbers, <dfn> without its English term, changed operators in maths lines
   --verbose lists every item.  --stats prints sizes per page.  With page ids, only those are checked.
   It always rewrites i18n/<lang>/index.js (the list of overlay files the site may load).
   Exit code 1 if anything is stale or fails a lint, or (without page ids) anything is missing.          */
'use strict';
const fs = require('fs');
const path = require('path');
const lib = require('./i18n-lib');

(async () => {
  const args = process.argv.slice(2);
  const pos = args.filter(a => !a.startsWith('--'));
  const lang = pos[0], only = pos.slice(1).map(s => s.replace(/\.q$/, ''));
  if (!lang) { console.error('Usage: node tools/i18n-check.js <lang> [pageId ...] [--verbose] [--stats] [--all] [--no-manifest]'); process.exit(2); }
  const dir = path.join(lib.ROOT, 'i18n', lang);
  if (!fs.existsSync(dir)) { console.error('No folder i18n/' + lang); process.exit(2); }
  const verbose = args.includes('--verbose'), stats = args.includes('--stats');
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.js') && f !== 'index.js').map(f => f.slice(0, -3));
  const order = s => (s === 'ui' ? '0' : s === 'common' ? '1' : '2' + s);
  files.sort((a, b) => order(a).localeCompare(order(b)));
  if (!args.includes('--no-manifest')) {
    fs.writeFileSync(path.join(dir, 'index.js'), '/* Generated by tools/i18n-check.js: the overlay files that exist for this language. */\n' +
      "S1.i18n.manifest('" + lang + "', " + JSON.stringify(files) + ');\n');
  }
  let scopes = [...new Set(files.map(f => f.replace(/\.q$/, '')))].filter(s => s !== 'common');
  if (!args.includes('--all')) scopes = scopes.filter(s => s !== 'dev');     // dev.js is a test fixture
  if (only.length) scopes = scopes.filter(s => only.includes(s));
  const common = lib.readOverlay(path.join(dir, 'common.js')) || { strings: {} };
  const commonKeys = {}; Object.keys(common.strings).forEach(k => { if (common.strings[k]) commonKeys[lib.norm(k)] = common.strings[k]; });

  const { chromium } = require('playwright');
  const browser = await chromium.launch();
  let bad = 0, missingTotal = 0;
  const pct = (a, b) => (b ? Math.round(100 * a / b) : 100) + '%';
  for (const scope of scopes) {
    let cat;
    try { cat = await lib.catalog(browser, scope); } catch (e) { console.log(scope.padEnd(10) + ' no English page for this file (orphan)'); bad++; continue; }
    const page = lib.readOverlay(path.join(dir, scope + '.js')) || { strings: {}, questions: {} };
    const qf = lib.readOverlay(path.join(dir, scope + '.q.js')) || { strings: {}, questions: {} };
    const have = {}; Object.keys(page.strings).forEach(k => { have[lib.norm(k)] = page.strings[k]; });
    const trQ = Object.assign({}, page.questions); Object.keys(qf.questions).forEach(id => { trQ[id] = Object.assign(trQ[id] || {}, qf.questions[id]); });
    const keys = cat.entries.map(e => e.key);
    const missing = keys.filter(k => !have[k] && !(scope !== 'ui' && commonKeys[k]));
    const stale = Object.keys(have).filter(k => !keys.includes(k));
    const lints = [];
    cat.entries.forEach(e => { const tr = have[e.key]; if (tr) lib.lintPair(e.key, tr, { math: e.kind === 'maths line', lang }).forEach(p => lints.push([e.key, p])); });
    const qMissing = [], qStale = [], qLint = [];
    let qFields = 0, qDone = 0, chars = keys.reduce((n, k) => n + k.replace(/<[^>]+>/g, '').length, 0), qChars = 0;
    Object.keys(cat.questions).forEach(id => {
      lib.questionPairs(cat.questions[id], trQ[id]).forEach(([p, en, tr]) => {
        qFields++; qChars += String(en).replace(/<[^>]+>/g, '').length;
        if (!tr) { qMissing.push(id + '.' + p); return; }
        qDone++;
        lib.lintPair(String(en), tr, { lang }).forEach(x => qLint.push([id + '.' + p, x]));
      });
    });
    Object.keys(trQ).forEach(id => { if (!cat.questions[id]) qStale.push(id); });
    const done = keys.length - missing.length;
    console.log(scope.padEnd(9) + ' strings ' + String(done).padStart(4) + '/' + String(keys.length).padEnd(4) + ' ' + pct(done, keys.length).padStart(4) +
      '  missing ' + missing.length + '  stale ' + stale.length + '  lint ' + lints.length +
      (qFields || qStale.length ? '   |  question fields ' + qDone + '/' + qFields + ' ' + pct(qDone, qFields) + '  missing ' + qMissing.length + '  stale ' + qStale.length + '  lint ' + qLint.length : ''));
    if (stats) console.log('          stats: page blocks ' + cat.counts.blocks + ', attributes ' + cat.counts.attrs + ', widget strings ' + cat.counts.widget + (cat.counts.shell ? ', shell strings ' + cat.counts.shell : '') +
      ', question fields ' + qFields + ' in ' + Object.keys(cat.questions).length + ' questions; English characters: ' + chars + ' (page) + ' + qChars + ' (questions); translated ' + pct(done + qDone, keys.length + qFields));
    const show = verbose || only.length;
    lints.forEach(([k, p]) => console.log('    LINT     ' + p + '\n             in: ' + k.slice(0, 110)));
    qLint.forEach(([k, p]) => console.log('    LINT     ' + p + '\n             in: ' + k));
    stale.forEach(k => { const c = lib.closest(k, missing); console.log('    STALE    ' + k.slice(0, 140) + (c ? '\n             closest current English (' + Math.round(c.score * 100) + '% alike): ' + c.key.slice(0, 140) : '')); });
    qStale.forEach(k => console.log('    STALE    question ' + k + ' no longer exists'));
    if (show) { missing.forEach(k => console.log('    MISSING  ' + k.slice(0, 140))); qMissing.forEach(k => console.log('    MISSING  ' + k)); }
    bad += stale.length + lints.length + qStale.length + qLint.length;
    missingTotal += missing.length + qMissing.length;
  }
  // common.js has no English page of its own: lint its pairs only
  if (!only.length && Object.keys(commonKeys).length) {
    let n = 0;
    Object.keys(commonKeys).forEach(k => lib.lintPair(k, commonKeys[k], { lang }).forEach(p => { n++; console.log('    LINT     ' + p + '\n             in common: ' + k.slice(0, 110)); }));
    console.log('common    ' + Object.keys(commonKeys).length + ' shared strings  lint ' + n);
    bad += n;
  }
  await browser.close();
  const fail = bad > 0 || (!only.length && missingTotal > 0);
  console.log(bad || missingTotal ? '\n' + bad + ' problem(s) to fix (stale or lint), ' + missingTotal + ' not translated yet.' + (verbose || only.length ? '' : ' Add --verbose to list the missing ones.') : '\nAll translated, nothing stale, all lints pass.');
  process.exit(fail ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
