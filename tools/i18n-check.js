#!/usr/bin/env node
/* Report missing and stale translations, and refresh the manifest.
     node tools/i18n-check.js <lang> [--verbose] [--no-manifest]
   For every i18n/<lang>/<scope>.js it compares the file with the English source:
     missing = key exists in English but has no translation
     stale   = key is in the file but no longer exists in English (the English was edited)
   It also rewrites i18n/<lang>/index.js, the list of overlay files the site may load.
   Exit code 1 if anything is missing or stale.                                         */
'use strict';
const fs = require('fs');
const path = require('path');
const lib = require('./i18n-lib');

(async () => {
  const args = process.argv.slice(2);
  const lang = args.find(a => !a.startsWith('--'));
  if (!lang) { console.error('Usage: node tools/i18n-check.js <lang> [--verbose] [--no-manifest]'); process.exit(2); }
  const dir = path.join(lib.ROOT, 'i18n', lang);
  if (!fs.existsSync(dir)) { console.error('No folder i18n/' + lang); process.exit(2); }
  const scopes = fs.readdirSync(dir).filter(f => f.endsWith('.js') && f !== 'index.js').map(f => f.slice(0, -3)).sort((a, b) => (a === 'ui' ? -1 : b === 'ui' ? 1 : a.localeCompare(b)));
  // i18n/<lang>/dev.js is a test fixture for dev/kitchen-sink.html: listed in the manifest, not checked unless --all.
  const checked = args.includes('--all') ? scopes : scopes.filter(sc => sc !== 'dev');
  if (!args.includes('--no-manifest')) {
    fs.writeFileSync(path.join(dir, 'index.js'), '/* Generated by tools/i18n-check.js: the overlay files that exist for this language. */\n' +
      "S1.i18n.manifest('" + lang + "', " + JSON.stringify(scopes) + ');\n');
  }
  const { chromium } = require('playwright');
  const browser = await chromium.launch();
  let bad = 0;
  for (const scope of checked) {
    let cat;
    try { cat = await lib.catalog(browser, scope); } catch (e) { console.log(scope.padEnd(10) + ' no English page for this file (orphan)'); bad++; continue; }
    const data = lib.readOverlay(path.join(dir, scope + '.js'));
    const have = {};
    Object.keys(data.strings).forEach(k => { have[lib.norm(k)] = data.strings[k]; });
    const missing = cat.strings.filter(k => !have[k]);
    const stale = Object.keys(have).filter(k => !cat.strings.includes(k));
    let qMissing = [], qStale = [];
    Object.keys(cat.questions).forEach(id => {
      const sk = lib.questionSkeleton(cat.questions[id]), tr = data.questions[id] || {};
      Object.keys(sk).forEach(f => {
        if (Array.isArray(sk[f])) sk[f].forEach((v, i) => { if (!(tr[f] && tr[f][i])) qMissing.push(id + '.' + f + '[' + i + ']'); });
        else if (typeof sk[f] === 'object') Object.keys(sk[f]).forEach(k => { if (!(tr[f] && tr[f][k])) qMissing.push(id + '.' + f + '.' + k); });
        else if (!tr[f]) qMissing.push(id + '.' + f);
      });
    });
    Object.keys(data.questions).forEach(id => { if (!cat.questions[id]) qStale.push(id); });
    const total = cat.strings.length + Object.keys(cat.questions).length;
    console.log(scope.padEnd(10) + ' strings ' + (cat.strings.length - missing.length) + '/' + cat.strings.length +
      '  missing ' + missing.length + '  stale ' + stale.length + '  |  question fields missing ' + qMissing.length + '  stale questions ' + qStale.length + (total ? '' : '  (empty)'));
    if (args.includes('--verbose')) {
      missing.forEach(k => console.log('    MISSING  ' + k));
      stale.forEach(k => console.log('    STALE    ' + k));
      qMissing.forEach(k => console.log('    MISSING  ' + k));
      qStale.forEach(k => console.log('    STALE    ' + k));
    }
    bad += missing.length + stale.length + qMissing.length + qStale.length;
  }
  await browser.close();
  console.log(bad ? '\n' + bad + ' problem(s). Run with --verbose to list them.' : '\nAll translated, nothing stale.');
  process.exit(bad ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
